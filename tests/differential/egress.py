"""Transport-level egress blocking for spawned test processes (WP6 [6A]).

The pytest session fixture installs this guard in-process; spawned test
processes consume it at interpreter startup through the environment marker, so
the block is in place before any provider module is imported.

Interface with WP1 [1C]'s spawn-time env pass-through — a spawner only carries
these variables, it never edits the child:

``VIBE_TEST_EGRESS_BLOCK``
    ``non_loopback`` denies every non-loopback INET destination and leaves
    loopback and AF_UNIX alone; ``all`` denies every INET destination (the
    differential replay default). Absent or empty disables the guard.
``VIBE_TEST_EGRESS_GUARD``
    Absolute path of this module. The generated ``sitecustomize`` loads it by
    path during interpreter startup and fails the process when it cannot, so a
    broken guard never degrades into silent egress.

The marker is deliberately outside the ``CHARTREUX_`` namespace: the config
environment layer treats any unknown ``CHARTREUX_*`` name as a fatal
configuration error, so a harness marker there would break every spawned agent
that loads configuration.

The guard patches ``socket.socket.connect`` / ``connect_ex``, which is where
TCP egress (including TLS, through ``SSLSocket``'s ``super().connect``) crosses
the transport. Running this module with a ``host`` and ``port`` probes the
block from inside an already-guarded child for a trace assertion.
"""

from __future__ import annotations

from collections.abc import Callable, Iterator, Sequence
from contextlib import contextmanager
import ipaddress
import json
import os
from pathlib import Path
import socket
import sys
import tempfile

EGRESS_BLOCK_ENV = "VIBE_TEST_EGRESS_BLOCK"
EGRESS_GUARD_ENV = "VIBE_TEST_EGRESS_GUARD"
MODE_NON_LOOPBACK = "non_loopback"
MODE_ALL = "all"
MODES = (MODE_NON_LOOPBACK, MODE_ALL)

_BLOCKED_MESSAGE = "provider network blocked by test isolation"
_MALFORMED_MESSAGE = "malformed socket address blocked by test isolation"
_LOOPBACK_HOSTS = frozenset({"localhost", "127.0.0.1", "::1", "::", "0.0.0.0"})
_INSTALLED_ATTRIBUTE = "_chartreux_test_egress_mode"
_GUARD_PATH = Path(__file__).resolve()

_SITECUSTOMIZE_SOURCE = '''\
"""Generated by tests/differential/egress.py: apply the egress marker at startup."""

import importlib.util
import os
import sys

# CPython reports a failed ``sitecustomize`` import and then continues, so the
# bootstrap terminates the process itself: a marker without a working guard
# must never degrade into an unguarded run.
_EGRESS_FAILURE_EXIT_CODE = 97


def _fail(message):
    sys.stderr.write(message + "\\n")
    sys.stderr.flush()
    os._exit(_EGRESS_FAILURE_EXIT_CODE)


_mode = os.environ.get("{marker}")
if _mode:
    _guard_path = os.environ.get("{guard_env}")
    if not _guard_path:
        _fail("egress marker set without {guard_env}")
    _spec = importlib.util.spec_from_file_location(
        "_chartreux_test_egress_guard", _guard_path
    )
    if _spec is None or _spec.loader is None:
        _fail("cannot load the egress guard from " + _guard_path)
    try:
        _guard = importlib.util.module_from_spec(_spec)
        _spec.loader.exec_module(_guard)
        _guard.apply_from_env()
    except BaseException as exc:
        _fail("egress guard failed: " + repr(exc))
'''

#: Exit status of a child whose guard bootstrap could not be installed.
EGRESS_BOOTSTRAP_FAILURE_EXIT_CODE = 97


def installed_mode() -> str | None:
    """Return the mode the transport guard is running with in this process."""
    value = getattr(socket, _INSTALLED_ATTRIBUTE, None)
    return value if isinstance(value, str) else None


def _is_blocked(address: object, mode: str) -> bool:
    if not isinstance(address, tuple):
        return False
    if len(address) != 2:
        raise OSError(_MALFORMED_MESSAGE)
    if mode == MODE_ALL:
        return True
    host = address[0]
    if host in _LOOPBACK_HOSTS:
        return False
    try:
        return not ipaddress.ip_address(host).is_loopback
    except (TypeError, ValueError):
        return True


def install(mode: str) -> Callable[[], None]:
    """Patch the socket transport and return the restoring callable."""
    if mode not in MODES:
        raise ValueError(f"unknown egress block mode: {mode!r}")
    original_connect = socket.socket.connect
    original_connect_ex = socket.socket.connect_ex

    def guarded_connect(self: socket.socket, address: object) -> object:
        if _is_blocked(address, mode):
            raise OSError(_BLOCKED_MESSAGE)
        return original_connect(self, address)  # type: ignore[arg-type]

    def guarded_connect_ex(self: socket.socket, address: object) -> int:
        if _is_blocked(address, mode):
            return 111
        return original_connect_ex(self, address)  # type: ignore[arg-type]

    socket.socket.connect = guarded_connect  # type: ignore[method-assign]
    socket.socket.connect_ex = guarded_connect_ex  # type: ignore[method-assign]
    setattr(socket, _INSTALLED_ATTRIBUTE, mode)

    def restore() -> None:
        socket.socket.connect = original_connect  # type: ignore[method-assign]
        socket.socket.connect_ex = original_connect_ex  # type: ignore[method-assign]
        setattr(socket, _INSTALLED_ATTRIBUTE, None)

    return restore


def apply_from_env() -> bool:
    """Install the guard the marker asks for; False when the marker is absent."""
    mode = os.environ.get(EGRESS_BLOCK_ENV, "")
    if not mode:
        return False
    install(mode)
    return True


def child_environment(mode: str) -> dict[str, str]:
    """The spawn-env additions that make a child consume the marker."""
    if mode not in MODES:
        raise ValueError(f"unknown egress block mode: {mode!r}")
    return {EGRESS_BLOCK_ENV: mode, EGRESS_GUARD_ENV: str(_GUARD_PATH)}


@contextmanager
def bootstrap_directory() -> Iterator[Path]:
    """A temporary directory holding the ``sitecustomize`` that applies the marker."""
    with tempfile.TemporaryDirectory(prefix="chartreux-egress-guard-") as directory:
        path = Path(directory)
        (path / "sitecustomize.py").write_text(
            _SITECUSTOMIZE_SOURCE.format(
                marker=EGRESS_BLOCK_ENV, guard_env=EGRESS_GUARD_ENV
            ),
            encoding="utf-8",
        )
        yield path


def probe(host: str, port: int, *, timeout: float = 1.0) -> dict[str, object]:
    """Attempt one transport connect and report its outcome instead of raising."""
    try:
        connection = socket.create_connection((host, port), timeout=timeout)
    except OSError as exc:
        return {
            "outcome": "denied",
            "error_type": type(exc).__name__,
            "error": str(exc),
        }
    connection.close()
    return {"outcome": "connected"}


def _probe_main(argv: Sequence[str]) -> int:
    if len(argv) != 2:
        raise SystemExit("usage: python -m tests.differential.egress HOST PORT")
    print(json.dumps(probe(argv[0], int(argv[1]))))
    return 0


if __name__ == "__main__":
    raise SystemExit(_probe_main(sys.argv[1:]))
